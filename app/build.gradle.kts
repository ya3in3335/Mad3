// Release signing is only configured when ALL credentials are supplied explicitly
// through environment variables (e.g. GitHub Actions secrets). Nothing is committed.
val releaseKeystorePath: String? = System.getenv("SAMTEX_KEYSTORE_PATH")
val releaseKeystorePassword: String? = System.getenv("SAMTEX_KEYSTORE_PASSWORD")
val releaseKeyAlias: String? = System.getenv("SAMTEX_KEY_ALIAS")
val releaseKeyPassword: String? = System.getenv("SAMTEX_KEY_PASSWORD")
val hasReleaseSigning = listOf(releaseKeystorePath, releaseKeystorePassword, releaseKeyAlias, releaseKeyPassword)
    .all { !it.isNullOrBlank() } && file(releaseKeystorePath!!).exists()

